"""Career mode data (ADR-047): looks and unlock rules in career_data.h."""
import json

from .common import AssetError, bgr15, paths

RULES = ("WINS", "RALLY", "ACES", "SHUTOUTS", "STREAK", "BEAT", "CLEARS",
         "OPEN")
NAME_CELLS = 12
LOCKED_NONE = 0xff
MAX_UNLOCKS = 16                # a u16 mask per player


def load_career():
    spec = json.loads((paths.src / "career.json").read_text("utf-8"))
    opponents = json.loads((paths.src / "opponents.json").read_text("utf-8"))
    frames = json.loads(paths.manifest.read_text("utf-8"))
    teams = [o["team"] for o in opponents["opponents"]]

    unlocks = spec["unlocks"]
    if not 1 <= len(unlocks) <= MAX_UNLOCKS:
        raise AssetError(f"career: 1..{MAX_UNLOCKS} unlocks")
    names = [u["name"] for u in unlocks]
    if len(set(names)) != len(names):
        raise AssetError("career: unlock names must be unique")
    rules = []
    for u in unlocks:
        if len(u["name"]) > NAME_CELLS:
            raise AssetError(f"career unlock {u['name']}: names fit "
                             f"{NAME_CELLS} cells")
        if u["rule"] not in RULES:
            raise AssetError(f"career unlock {u['name']}: rule is one of "
                             f"{', '.join(RULES)}")
        value = u["value"]
        if u["rule"] == "BEAT":
            if value not in teams:
                raise AssetError(f"career unlock {u['name']}: no ladder "
                                 f"team {value}")
            value = teams.index(value)
        elif not 1 <= value <= 9999:
            raise AssetError(f"career unlock {u['name']}: value 1..9999")
        rules.append((u["name"], RULES.index(u["rule"]), value))

    def locked_by(entry, kind):
        """The unlock named after a choice's own fields, or LOCKED_NONE."""
        fields = 2 if kind == "hair" else 1         # name (and colour)
        if len(entry) == fields:
            return LOCKED_NONE
        name = entry[-1]
        if name not in names:
            raise AssetError(f"career {kind} {entry[0]}: no unlock {name}")
        return names.index(name)

    skins = spec["skins"]
    if [s.lower() for s in skins] != list(opponents["skins"]):
        raise AssetError("career: skins name opponents.json's skins in order")
    hair = []
    for entry in spec["hair"]:
        if len(entry[0]) > 8:
            raise AssetError(f"career hair {entry[0]}: names fit 8 cells")
        if len(entry[1]) != 3 or not all(0 <= c <= 31 for c in entry[1]):
            raise AssetError(f"career hair {entry[0]}: 5-bit RGB")
        hair.append((entry[0], bgr15(*entry[1]), locked_by(entry, "hair")))
    if hair[0][2] != LOCKED_NONE:
        raise AssetError("career: the first hair colour is always available")
    hats = []
    hat_order = ["CAP"] + [h.upper() for h in frames["hats"]]
    shown = [h[0] for h in spec["hats"]]
    if len(shown) != len(hat_order) or shown[:-1] != hat_order[:-1]:
        raise AssetError("career: hats follow player_frames.json (CAP, then "
                         "its hats; the bare-hair hat last, any name)")
    for entry in spec["hats"]:
        hats.append((entry[0], locked_by(entry, "hat")))
    if hats[0][1] != LOCKED_NONE:
        raise AssetError("career: the cap is always available")
    return skins, opponents["skins"], hair, hats, rules


def career_header():
    skins, skin_parts, hair, hats, rules = load_career()
    lines = ["/* Generated by tools/generate_assets.py from "
             "assets/source/career.json; do not edit. */",
             "#ifndef CAREER_DATA_H", "#define CAREER_DATA_H", "",
             "#include \"game_types.h\"", "",
             f"#define CAREER_SKINS {len(skins)}",
             f"#define CAREER_HAIRS {len(hair)}",
             f"#define CAREER_HATS {len(hats)}",
             f"#define CAREER_UNLOCKS {len(rules)}",
             f"#define CAREER_FREE 0x{LOCKED_NONE:02x}",
             "/* Unlock rules (ADR-047). */"]
    for i, rule in enumerate(RULES):
        lines.append(f"#define CAREER_RULE_{rule} {i}")
    lines += ["", "#ifdef CAREER_DATA_DEFINE"]
    lines.append("const char *const g_career_skin_names[CAREER_SKINS] = { " +
                 ", ".join(f'"{s}"' for s in skins) + " };")
    lines.append("/* Skin ramps (palette 2-4), from opponents.json. */")
    lines.append("const u16 g_career_skins[CAREER_SKINS][3] = { " + ", ".join(
        "{ " + ", ".join(f"0x{bgr15(*c):04x}" for c in skin_parts[s]) + " }"
        for s in skin_parts) + " };")
    lines.append("const char *const g_career_hair_names[CAREER_HAIRS] = { " +
                 ", ".join(f'"{h[0]}"' for h in hair) + " };")
    lines.append("const u16 g_career_hair[CAREER_HAIRS] = { " +
                 ", ".join(f"0x{h[1]:04x}" for h in hair) + " };")
    lines.append("/* The unlock that frees each choice, or CAREER_FREE. */")
    lines.append("const u8 g_career_hair_unlock[CAREER_HAIRS] = { " +
                 ", ".join(f"0x{h[2]:02x}" for h in hair) + " };")
    lines.append("const char *const g_career_hat_names[CAREER_HATS] = { " +
                 ", ".join(f'"{h[0]}"' for h in hats) + " };")
    lines.append("const u8 g_career_hat_unlock[CAREER_HATS] = { " +
                 ", ".join(f"0x{h[1]:02x}" for h in hats) + " };")
    lines.append("const char *const g_career_unlock_names[CAREER_UNLOCKS] "
                 "= { " + ", ".join(f'"{r[0]}"' for r in rules) + " };")
    lines.append("const u8 g_career_unlock_rule[CAREER_UNLOCKS] = { " +
                 ", ".join(str(r[1]) for r in rules) + " };")
    lines.append("const u16 g_career_unlock_value[CAREER_UNLOCKS] = { " +
                 ", ".join(str(r[2]) for r in rules) + " };")
    lines += ["#else",
              "extern const char *const g_career_skin_names[CAREER_SKINS];",
              "extern const u16 g_career_skins[CAREER_SKINS][3];",
              "extern const char *const g_career_hair_names[CAREER_HAIRS];",
              "extern const u16 g_career_hair[CAREER_HAIRS];",
              "extern const u8 g_career_hair_unlock[CAREER_HAIRS];",
              "extern const char *const g_career_hat_names[CAREER_HATS];",
              "extern const u8 g_career_hat_unlock[CAREER_HATS];",
              "extern const char *const g_career_unlock_names[CAREER_UNLOCKS];",
              "extern const u8 g_career_unlock_rule[CAREER_UNLOCKS];",
              "extern const u16 g_career_unlock_value[CAREER_UNLOCKS];",
              "#endif", "", "#endif", ""]
    return "\n".join(lines)
