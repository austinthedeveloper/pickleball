"""Paddle stats (ADR-020): validated modifier tables in paddle_stats.h."""
import json
import re

from .common import ROOT, AssetError, paths

BOUND_64THS = 9.6   # +/-15% of 64 (ADR-015)


def player_tunable(name):
    text = (ROOT / "include" / "player.h").read_text("utf-8")
    match = re.search(rf"\b{name} = (\d+)", text)
    if not match:
        raise AssetError(f"include/player.h: {name} not found")
    return int(match.group(1))


def load_paddles():
    spec = json.loads((paths.src / "paddles.json").read_text("utf-8"))
    names = [p["name"] for p in spec["paddles"]]
    if spec["standard"] not in names:
        raise AssetError("paddles.json: standard paddle is not listed")
    for paddle in spec["paddles"]:
        stats = [paddle[k] for k in ("power", "control", "speed")]
        if any(not 0 <= s <= spec["scale_max"] for s in stats):
            raise AssetError(f"paddle {paddle['name']}: stat outside "
                             f"0..{spec['scale_max']}")
        if sum(stats) != spec["budget"]:
            raise AssetError(f"paddle {paddle['name']}: stats sum to "
                             f"{sum(stats)}, budget is {spec['budget']}")
    return spec


def paddle_tables(spec):
    """Per-paddle integer modifiers; every one within +/-15% of baseline."""
    swing = player_tunable("PLAYER_SWING_MAX_SPEED_FP")
    recovery = player_tunable("PLAYER_RECOVERY_FRAMES")
    step = spec["step_64ths"]
    rows = []
    for paddle in spec["paddles"]:
        kp = paddle["power"] - spec["baseline"]
        kc = paddle["control"] - spec["baseline"]
        ks = paddle["speed"] - spec["baseline"]
        power = 64 + step * kp
        control = 64 - step * kc
        swing_mul = 64 + step * ks
        swing_limit = (swing * swing_mul + 32) // 64
        rec = recovery - int(ks / 2)
        for label, value, base in (("power", power, 64),
                                   ("control", control, 64),
                                   ("swing limit", swing_limit, swing),
                                   ("recovery", rec, recovery)):
            if abs(value - base) > base * 0.15:
                raise AssetError(f"paddle {paddle['name']}: {label} {value} "
                                 f"is more than 15% from {base}")
        rows.append((paddle, power, control, swing_limit, rec))
    return rows


def paddle_stats_header():
    spec = load_paddles()
    rows = paddle_tables(spec)
    names = [p["name"] for p in spec["paddles"]]
    lines = ["/* Generated by tools/generate_assets.py from "
             "assets/source/paddles.json; do not edit. */",
             "#ifndef PADDLE_STATS_H", "#define PADDLE_STATS_H", "",
             "#include \"game_types.h\"", ""]
    for i, name in enumerate(names):
        lines.append(f"#define PADDLE_{name.upper()} {i}")
    lines += [f"#define PADDLE_COUNT {len(names)}",
              f"#define PADDLE_STANDARD PADDLE_{spec['standard'].upper()}",
              f"#define PADDLE_STAT_MAX {spec['scale_max']}", "",
              "#ifdef PADDLE_STATS_DEFINE"]

    def table(ctype, name, values):
        return (f"const {ctype} {name}[PADDLE_COUNT] = {{ " +
                ", ".join(str(v) for v in values) + " };")
    lines.append("/* Bars: power, control, speed. */")
    lines.append("const u8 g_paddle_stats[PADDLE_COUNT][3] = { " + ", ".join(
        "{ %d, %d, %d }" % (p["power"], p["control"], p["speed"])
        for p, *_ in rows) + " };")
    lines.append("/* Shot pace x n / 64. */")
    lines.append(table("u8", "g_paddle_power_mul", [r[1] for r in rows]))
    lines.append("/* Stretch spray x n / 64. */")
    lines.append(table("u8", "g_paddle_control_mul", [r[2] for r in rows]))
    lines.append("/* Movement limit while swinging, 12.4 units. */")
    lines.append(table("u8", "g_paddle_swing_limit", [r[3] for r in rows]))
    lines.append("/* Recovery frames after a swing. */")
    lines.append(table("u8", "g_paddle_recovery", [r[4] for r in rows]))
    lines += ["#else",
              "extern const u8 g_paddle_stats[PADDLE_COUNT][3];",
              "extern const u8 g_paddle_power_mul[PADDLE_COUNT];",
              "extern const u8 g_paddle_control_mul[PADDLE_COUNT];",
              "extern const u8 g_paddle_swing_limit[PADDLE_COUNT];",
              "extern const u8 g_paddle_recovery[PADDLE_COUNT];",
              "#endif", "", "#endif", ""]
    return "\n".join(lines), names
