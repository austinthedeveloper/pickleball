"""OBJ sheet (player frames and small objects) and palette parts."""
import json
import struct

from .common import (OBJ_TABLE1_SLOTS, OBJ_TILE_BUDGET, AssetError, bgr15,
                     block, encode_tile, paths, read_png)


def slot_tile(slot):
    """OBJ tile number of a player sheet slot's top-left 8x8 tile.

    Slots 0-11 (sheet rows 0-2) are tiles 0-191 of name table 1; the
    objects and park fonts follow them there (the park writes u8 tiles).
    Slots from 12 (rows 3-6) are name table 2 (tiles 256-511, VRAM word
    0x7000), which oam_write reaches through the attribute's N bit. A
    32x32 object's tiles wrap inside one table, and four 4-tile columns
    per 16-tile row keep each frame inside its own."""
    if slot < OBJ_TABLE1_SLOTS:
        return (slot // 4) * 64 + (slot % 4) * 4
    slot -= OBJ_TABLE1_SLOTS
    return 256 + (slot // 4) * 64 + (slot % 4) * 4

def load_part(name):
    return json.loads((paths.palettes / f"{name}.json").read_text("utf-8"))


def palette_parts_header(colors, paddle_names):
    """Contract v2 parts for runtime composition (ADR-013)."""
    shared = load_part("shared")
    skin = load_part("skin_light")
    lines = ["/* Generated by tools/generate_assets.py from "
             "assets/source/palettes; do not edit. */",
             "#ifndef PALETTE_PARTS_H", "#define PALETTE_PARTS_H", "",
             "#include \"game_types.h\"", ""]
    for i, name in enumerate(colors):
        lines.append(f"#define PAL_{name.upper()} {i}")
    lines += [f"#define PAL_COUNT {len(colors)}", "#define SKIN_COUNT 1",
              f"#define PADDLE_PART_COUNT {len(paddle_names)}", "",
              "#ifdef PALETTE_PARTS_DEFINE"]

    def arr(name, rows):
        body = ",\n    ".join("{ " + ", ".join(str(bgr15(*c)) for c in row)
                               + " }" for row in rows)
        return f"const u16 {name}[{len(rows)}][{len(rows[0])}] = {{\n    {body}\n}};"
    teams = [load_part(f"team_{n}") for n in colors]
    paddles = [load_part(f"paddle_{n}") for n in paddle_names]
    lines.append(arr("g_pal_shared", [[shared["outline"], shared["highlight"]]]))
    lines.append(arr("g_pal_skin", [skin["skin"] + [skin["hair"]]]))
    lines.append(arr("g_pal_team", [t["shirt"] + t["shorts"] + [t["shoe"]]
                                    for t in teams]))
    lines.append(arr("g_pal_paddle", [p["face"] + [p["edge"]] for p in paddles]))
    lines.append(arr("g_pal_hud", [t["hud"] for t in teams]))
    flash = [0] + [bgr15(31, 31, 24)] * 15
    flash[1] = bgr15(31, 24, 8)
    lines.append("const u16 g_pal_flash[16] = { " +
                 ", ".join(str(v) for v in flash) + " };")
    lines += ["#else",
              "extern const u16 g_pal_shared[1][2];",
              "extern const u16 g_pal_skin[SKIN_COUNT][4];",
              "extern const u16 g_pal_team[PAL_COUNT][6];",
              "extern const u16 g_pal_paddle[PADDLE_PART_COUNT][3];",
              "extern const u16 g_pal_hud[PAL_COUNT][2];",
              "extern const u16 g_pal_flash[16];",
              "#endif", "", "#endif", ""]
    return "\n".join(lines)


# Contract v2: every index 1..15 is a declared role (ADR-013).
V2_ROLES = set(range(1, 16))

OBJECT_PALETTE = [0, bgr15(6, 6, 2), bgr15(28, 29, 6), bgr15(31, 31, 24),
                  bgr15(0, 0, 0), bgr15(31, 27, 8), bgr15(31, 31, 31),
                  # 7-9: the practice ball machine's greys (ADR-028).
                  bgr15(10, 11, 13), bgr15(17, 18, 20), bgr15(24, 25, 26)] + \
    [0] * 6
# Shadows draw with OBJ palette 4 so color math halves the court behind them.
SHADOW_PALETTE = [0, 0, 0, 0, bgr15(0, 0, 0)] + [0] * 11
# Doubles (ADR-018): shadows are opaque because colour math is off.
SHADOW_OPAQUE_PALETTE = [0, 0, 0, 0, bgr15(4, 7, 7)] + [0] * 11


# The park's court labels and scores as sprites (M4-OPEN-05: BG3 text
# can't scroll with the park): HUD font glyphs, outlined in black, in the
# objects palette. Yellow (2) for the scores, white (6) for the labels.
PARK_FONTS = (("YELLOW", "0123456789-NEXTYOU", 2), ("WHITE", "<.+-345", 6))


def font_tiles(chars, fill):
    from .hud import FONT
    tiles = []
    for ch in chars:
        glyph = FONT[ch]
        px = [[0] * 8 for _ in range(8)]
        for y, row in enumerate(glyph):
            for x, c in enumerate(row[:6]):
                if c == "#":
                    px[y][x + 1] = fill
        for y in range(8):
            for x in range(8):
                if px[y][x] == 0 and any(
                        0 <= y + dy < 8 and 0 <= x + dx < 8 and
                        px[y + dy][x + dx] == fill
                        for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                    px[y][x] = 4
        tiles.append(encode_tile(px, 4))
    return tiles


def obj_assets(manifest):
    width, height, rows, _ = read_png(paths.src / "player_sprites.png")
    if width != 128 or height % 32:
        raise AssetError("player_sprites.png must be 128 wide, rows of 32")
    frames = manifest["frames"]
    slots = (width // 32) * (height // 32)
    if slots > OBJ_TABLE1_SLOTS + 16:
        raise AssetError(f"OBJ uses {slots} sheet slots > "
                         f"{OBJ_TABLE1_SLOTS + 16} (name table 2 holds 16)")
    if len(frames) > slots:
        raise AssetError("more manifest frames than sheet slots")
    for name, info in frames.items():
        slot = info["slot"]
        x0, y0 = (slot % 4) * 32, (slot // 4) * 32
        px = block(rows, x0, y0, 32, 32)
        if any(v > 15 for row in px for v in row):
            raise AssetError(f"frame {name} uses color index > 15")
        if not any(v for row in px for v in row):
            raise AssetError(f"frame {name} is empty")
        foot = max(y for y in range(32) if any(px[y]))
        if foot != manifest["foot_row"]:
            raise AssetError(f"frame {name} foot row {foot} != "
                             f"{manifest['foot_row']}")
    ow, oh, orows, _ = read_png(paths.src / "objects.png")
    if ow != 128 or oh % 8 or not 8 <= oh <= 16:
        raise AssetError("objects.png must be 128x8 or 128x16 (rows of "
                         "sixteen 8x8 objects)")
    tiles = []
    table1_rows = min(height, OBJ_TABLE1_SLOTS // 4 * 32) // 8
    for ty in range(table1_rows):
        for tx in range(16):
            tiles.append(encode_tile(block(rows, tx * 8, ty * 8), 4))
    table2 = []
    for ty in range(table1_rows, height // 8):
        for tx in range(16):
            table2.append(encode_tile(block(rows, tx * 8, ty * 8), 4))
    object_base = len(tiles)
    for ty in range(oh // 8):
        for tx in range(16):
            tiles.append(encode_tile(block(orows, tx * 8, ty * 8), 4))
    if not PARK_FONTS[0][1].startswith("0123456789"):
        raise AssetError("the park's yellow font starts with the digits "
                         "(render_park.c: park_glyph)")
    font_base = {}
    for name, chars, fill in PARK_FONTS:
        font_base[name] = len(tiles)
        tiles += font_tiles(chars, fill)
    if len(tiles) > OBJ_TILE_BUDGET:
        raise AssetError(f"OBJ uses {len(tiles)} tiles > {OBJ_TILE_BUDGET} "
                         "in name table 1")
    if len(table2) > OBJ_TILE_BUDGET:
        raise AssetError(f"OBJ uses {len(table2)} tiles > {OBJ_TILE_BUDGET} "
                         "in name table 2")
    for name, info in frames.items():
        slot = info["slot"]
        x0, y0 = (slot % 4) * 32, (slot // 4) * 32
        used = {v for row in block(rows, x0, y0, 32, 32) for v in row} - {0}
        undeclared = used - V2_ROLES
        if undeclared:
            raise AssetError(f"frame {name} uses undeclared palette roles "
                             f"{sorted(undeclared)}")
    obj_pal = OBJECT_PALETTE + SHADOW_PALETTE + SHADOW_OPAQUE_PALETTE
    header = ["/* Generated by tools/generate_assets.py; do not edit. */",
              "#ifndef ASSET_FRAMES_H", "#define ASSET_FRAMES_H", ""]
    for name, info in frames.items():
        header.append(f"#define FRAME_{name.upper()} {slot_tile(info['slot'])}")
    names = list(frames)
    header.append(f"#define FRAME_COUNT {len(names)}")
    # ADR-014 ponytail offsets, top-left in frame pixels when facing right.
    for name, info in frames.items():
        ax, ay = info.get("accessory", (None, None))
        if ax is None or not (0 <= ax <= 24 and 0 <= ay <= 24):
            raise AssetError(f"frame {name}: accessory offset missing or "
                             "outside the 32x32 frame")
        header.append(f"#define FRAME_{name.upper()}_SLOT {info['slot']}")
        header.append(f"#define FRAME_{name.upper()}_INDEX "
                      f"{names.index(name)}")
        header.append(f"#define FRAME_{name.upper()}_ACC_X {ax}")
        header.append(f"#define FRAME_{name.upper()}_ACC_Y {ay}")
    for name, index in manifest["objects"].items():
        header.append(f"#define OBJTILE_{name.upper()} {object_base + index}")
    # M4-OPP-04 hats: two objects each (the cell and the next), on blank
    # objects.png cells; HAT_TILES[id] in the manifest's order, the cap
    # first (ADR-059: bodies are bareheaded). A null cell is no hat: the
    # bare head's hair, tile 0, which render_bodies parks.
    hat_tiles = []
    taken = set(manifest["objects"].values())
    if next(iter(manifest["hats"]), None) != "cap":
        raise AssetError("hats: the cap comes first (id 0, the default)")
    for name, cell in manifest["hats"].items():
        if cell is None:
            hat_tiles.append("0")
            continue
        # Even: render_bodies swaps the halves of a flipped hat as tile ^ 1.
        if cell % 2 or not 0 <= cell < (oh // 8) * 16 or \
                {cell, cell + 1} & taken:
            raise AssetError(f"hat {name}: cell {cell} is odd, off the "
                             "objects row, or taken")
        taken |= {cell, cell + 1}
        header.append(f"#define OBJTILE_HAT_{name.upper()} "
                      f"{object_base + cell}")
        hat_tiles.append(str(object_base + cell))
    dx, dy = manifest["hat_offset"]
    if not 0 <= dx <= 16 or not -8 <= dy <= 0:
        raise AssetError("hat_offset must be x 0..16, y -8..0 (a hat sits "
                         "on the head)")
    header.append(f"#define HAT_COUNT {len(hat_tiles)}")
    header.append(f"#define HAT_TILES {{ {', '.join(hat_tiles)} }}")
    header.append(f"#define HAT_DX {dx}")
    header.append(f"#define HAT_RAISE {-dy}")
    # 32x32 objects in sheet slots no frame uses (the BIG BALL, ADR-033).
    used_slots = {info["slot"] for info in frames.values()}
    for name, slot in manifest.get("large_objects", {}).items():
        if slot in used_slots or not 0 <= slot < slots:
            raise AssetError(f"large object {name}: slot {slot} is taken "
                             "or outside the sheet")
        x0, y0 = (slot % 4) * 32, (slot // 4) * 32
        if not any(v for row in block(rows, x0, y0, 32, 32) for v in row):
            raise AssetError(f"large object {name} is empty")
        header.append(f"#define OBJTILE_{name.upper()} {slot_tile(slot)}")
    for name, chars, _ in PARK_FONTS:
        header.append(f"#define OBJTILE_FONT_{name} {font_base[name]}")
        header.append(f'#define OBJFONT_{name} "{chars}"')
    cycles, tables = frame_cycles(manifest, names)
    header += cycles + ["", "#endif", ""]
    # Name table 2 starts at tile 256: pad table 1 when it is used.
    pic = tiles
    if table2:
        pic = tiles + [bytes(32)] * (OBJ_TILE_BUDGET - len(tiles)) + table2
    return b"".join(pic), struct.pack(f"<{len(obj_pal)}H", *obj_pal), \
        "\n".join(header), len(tiles) + len(table2), tables


def frame_cycles(manifest, names):
    """Animation loops and the renderer's per-frame tables.

    Returns the cycle defines for asset_frames.h and frame_tables.inc, the
    tables src/asm/render_bodies.asm indexes by frame index (manifest
    order), so a new frame or a longer loop touches no assembly. A loop's
    length is a power of two: the renderer masks the animation frame."""
    frames = manifest["frames"]
    defines, asm = [], ["; Generated by tools/generate_assets.py from "
                        "assets/manifest/player_frames.json; do not edit."]
    for name, loop in manifest["cycles"].items():
        count = len(loop)
        if count < 1 or count & (count - 1) or \
                any(cel not in frames for cel in loop):
            raise AssetError(f"cycle {name}: needs a power-of-two count of "
                             "manifest frames")
        defines.append(f"#define ANIM_{name.upper()}_CELS {count}")
        asm.append(f"_rb_{name}:")
        asm.append("    .dw " + ", ".join(str(names.index(c)) for c in loop))
    for label, value in (("tile", lambda i: slot_tile(i["slot"])),
                         ("acc_x", lambda i: i["accessory"][0]),
                         ("acc_y", lambda i: i["accessory"][1])):
        asm.append(f"_rb_{label}:")
        asm.append("    .dw " + ", ".join(str(value(frames[n]))
                                          for n in names))
    return defines, "\n".join(asm) + "\n"
