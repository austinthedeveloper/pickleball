"""Story mode (ADR-077): the partner's look and the scenes, in story_data.h."""
import json

from .common import AssetError, paths
from .opponents import (LINE_CELLS, LINE_CHARS, NAME_CELLS, VARIANTS,
                        compose)

WHO = ("chapter", "narrator", "partner", "captain", "mate", "villain", "end")
SPEAKERS = WHO[1:6]             # what a page in story.json may name
PAGES_MAX = 255                 # page indices are u8


def check_line(where, line):
    if not 1 <= len(line) <= LINE_CELLS or not LINE_CHARS.fullmatch(line):
        raise AssetError(f"{where}: {line!r} is 1..{LINE_CELLS} capitals, "
                         "digits, spaces, and .,!?'-:")
    return line


def scene_pages(where, pages):
    if not pages:
        raise AssetError(f"{where}: at least one page")
    out = []
    for n, page in enumerate(pages):
        at = f"{where} page {n + 1}"
        if page.get("who") not in SPEAKERS:
            raise AssetError(f"{at}: who is one of {', '.join(SPEAKERS)}")
        lines = page.get("lines", [])
        if not 1 <= len(lines) <= 2:
            raise AssetError(f"{at}: one or two lines")
        lines = [check_line(at, line) for line in lines]
        out.append((WHO.index(page["who"]), lines[0],
                    lines[1] if len(lines) > 1 else ""))
    return out


def story_header():
    spec = json.loads((paths.src / "story.json").read_text("utf-8"))
    opponents = json.loads((paths.src / "opponents.json").read_text("utf-8"))
    paddles = json.loads((paths.src / "paddles.json").read_text("utf-8"))
    paddle_names = [p["name"] for p in paddles["paddles"]]
    paddle_parts = {name: json.loads((paths.palettes / f"paddle_{name}.json")
                                     .read_text("utf-8"))
                    for name in paddle_names}
    shared = json.loads((paths.palettes / "shared.json").read_text("utf-8"))
    manifest = json.loads(paths.manifest.read_text("utf-8"))
    hat_names = list(manifest["hats"])
    celebrations = manifest.get("celebrations", ["cheer"])
    teams = opponents["opponents"]

    partner = spec["partner"]
    where = "story.json partner"
    names = [p["name"] for team in teams for p in team["players"]]
    if not 1 <= len(partner["name"]) <= NAME_CELLS or partner["name"] in names:
        raise AssetError(f"{where}: a name of 1..{NAME_CELLS} cells that no "
                         "ladder player has")
    if partner["variant"] not in VARIANTS:
        raise AssetError(f"{where}: variant is male or female")
    if partner["paddle"] not in paddle_names:
        raise AssetError(f"{where}: paddle is one of {', '.join(paddle_names)}")
    if partner["hat"] not in hat_names:
        raise AssetError(f"{where}: hat is one of {', '.join(hat_names)}")
    if partner.get("celebrate", "cheer") not in celebrations:
        raise AssetError(f"{where}: celebrate is one of "
                         f"{', '.join(celebrations)}")
    palette = compose(where, partner, opponents["skins"], shared, paddle_parts)
    villain = spec["villain"]
    if not 1 <= len(villain) <= NAME_CELLS or not LINE_CHARS.fullmatch(villain):
        raise AssetError(f"story.json villain: 1..{NAME_CELLS} capitals")

    chapters = spec["chapters"]
    if len(chapters) != len(teams):
        raise AssetError(f"story.json: one chapter per ladder team "
                         f"({len(teams)})")
    pages, first = [], []
    for n, chapter in enumerate(chapters):
        where = f"story.json chapter {n + 1}"
        first.append(len(pages))
        pages.append((WHO.index("chapter"),
                      check_line(where, chapter["title"]), ""))
        pages += scene_pages(where, chapter["pages"])
    first.append(len(pages))
    pages += scene_pages("story.json ending", spec["ending"]["pages"])
    pages.append((WHO.index("end"), "", ""))
    first.append(len(pages))
    if len(pages) > PAGES_MAX:
        raise AssetError(f"story.json: at most {PAGES_MAX} pages")

    def c_string(text):
        return f'"{text}"'

    lines = ["/* Generated by tools/generate_assets.py from "
             "assets/source/story.json; do not edit. */",
             "#ifndef STORY_DATA_H", "#define STORY_DATA_H", "",
             "#include \"game_types.h\"", "",
             f"#define STORY_CHAPTERS {len(chapters)}",
             "#define STORY_ENDING STORY_CHAPTERS  /* the scene after the "
             "last */",
             f"#define STORY_PAGES {len(pages)}", "",
             "/* Who speaks a page (g_story_who). CHAPTER and END are the "
             "scenes' own first and last pages. */",
             "enum { " + ", ".join(f"STORY_WHO_{w.upper()} = {i}"
                                   for i, w in enumerate(WHO)) + " };", "",
             "#ifdef STORY_DATA_DEFINE",
             f"const char g_story_partner_name[] = {c_string(partner['name'])};",
             f"const char g_story_villain[] = {c_string(villain)};",
             "/* The partner's full OBJ palette (ADR-013 roles), variant, "
             "paddle, hat, and celebration. */",
             "const u16 g_story_partner_palette[16] = { " +
             ", ".join(f"0x{w:04x}" for w in palette) + " };",
             f"const u8 g_story_partner_variant = "
             f"{VARIANTS.index(partner['variant'])};",
             f"const u8 g_story_partner_paddle = "
             f"{paddle_names.index(partner['paddle'])};",
             f"const u8 g_story_partner_hat = {hat_names.index(partner['hat'])};",
             f"const u8 g_story_partner_celebrate = "
             f"{celebrations.index(partner.get('celebrate', 'cheer'))};",
             "/* Each team's second player, for MATE pages. */",
             "const char *const g_story_mate[STORY_CHAPTERS] = { " +
             ", ".join(c_string(t["players"][1]["name"]) for t in teams) + " };",
             "/* Scene n is pages g_story_first[n] up to g_story_first[n + 1]; "
             "scene STORY_ENDING is the ending. */",
             "const u8 g_story_first[STORY_CHAPTERS + 2] = { " +
             ", ".join(map(str, first)) + " };",
             "const u8 g_story_who[STORY_PAGES] = { " +
             ", ".join(str(p[0]) for p in pages) + " };",
             "const char *const g_story_line1[STORY_PAGES] = {"]
    lines += [f"    {c_string(p[1])}," for p in pages]
    lines.append("};")
    lines.append("const char *const g_story_line2[STORY_PAGES] = {")
    lines += [f"    {c_string(p[2])}," for p in pages]
    lines.append("};")
    lines += ["#else",
              "extern const char g_story_partner_name[];",
              "extern const char g_story_villain[];",
              "extern const u16 g_story_partner_palette[16];",
              "extern const u8 g_story_partner_variant;",
              "extern const u8 g_story_partner_paddle;",
              "extern const u8 g_story_partner_hat;",
              "extern const u8 g_story_partner_celebrate;",
              "extern const char *const g_story_mate[STORY_CHAPTERS];",
              "extern const u8 g_story_first[STORY_CHAPTERS + 2];",
              "extern const u8 g_story_who[STORY_PAGES];",
              "extern const char *const g_story_line1[STORY_PAGES];",
              "extern const char *const g_story_line2[STORY_PAGES];",
              "#endif", "", "#endif", ""]
    return "\n".join(lines)
