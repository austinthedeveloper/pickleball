def asm_include(frames_header):
    """WLA-DX .defines from include/asm_shared.h and the frame tiles."""
    import re
    lines = ["; Generated by tools/generate_assets.py; do not edit."]
    sources = (paths.src.parents[1] / "include" / "asm_shared.h").read_text()
    for text in (sources, frames_header):
        for name, value in re.findall(r"#define (\w+) ((?:0x)?[0-9A-Fa-f]+)\s*$",
                                      text, re.M):
            lines.append(f".define {name} {value.replace('0x', '$')}")
    return "\n".join(lines) + "\n"


def generated_files():
    manifest = json.loads(paths.manifest.read_text(encoding="utf-8"))
    venue_files, court_tiles, ground_tiles = court_assets()
    hud_pic, hud_pal, big_chars, hud_tiles = hud_assets()
    obj_pic, objects_pal, header, obj_tiles, frame_tables = \
        obj_assets(manifest)
    paddle_header, paddle_names = paddle_stats_header()
    select_pic, select_map, select_pal, select_tiles = scene_assets()
    portrait_pic, portrait_m, portrait_f, portrait_tiles = portrait_assets()
    bust_pic, bust_m, bust_f, bust_tiles, closeup_map = bust_assets()
    park_pic, park_map, park_pal, park_tiles = park_assets()
    projection = court_projection.header(court_projection.scale_table())
    hud_header = [
        "/* Generated by tools/generate_assets.py; do not edit. */",
        "#ifndef HUD_TILES_H", "#define HUD_TILES_H",
        f"#define HUD_TILE_CLEAR {HUD_TILE_CLEAR}",
        f"#define HUD_TILE_PANEL_TL {HUD_TILE_PANEL_TL}",
        f"#define HUD_TILE_PANEL_T {HUD_TILE_PANEL_T}",
        f"#define HUD_TILE_PANEL_L {HUD_TILE_PANEL_L}",
        f"#define HUD_TILE_BUTTON_B {HUD_TILE_BUTTON_B}",
        f"#define HUD_TILE_CURSOR {HUD_TILE_CURSOR}",
        f"#define HUD_TILE_BAR_ON {HUD_TILE_BAR_ON}",
        f"#define HUD_TILE_BAR_OFF {HUD_TILE_BAR_OFF}",
        f"#define HUD_TILE_BALL_ICON {HUD_TILE_BALL_ICON}",
        f"#define HUD_TILE_DOT {HUD_TILE_DOT}",
        f"#define HUD_TILE_DOT_ALT {HUD_TILE_DOT_ALT}",
        f"#define HUD_TILE_X_OFF {HUD_TILE_X_OFF}",
        f"#define HUD_TILE_BIG_BASE {HUD_TILE_BIG_BASE}",
        f"#define HUD_BIG_CHARS \"{big_chars}\"",
        "#endif", ""]
    files = {
        "hud.pic": hud_pic,
        "hud.pal": hud_pal,
        "obj.pic": obj_pic,
        "objects.pal": objects_pal,
        "frame_tables.inc": frame_tables.encode(),
        "asset_frames.h": header.encode(),
        "hud_tiles.h": "\n".join(hud_header).encode(),
        "palette_parts.h": palette_parts_header(
            manifest["palettes"], paddle_names).encode(),
        "paddle_stats.h": paddle_header.encode(),
        "court_colors.h": court_colors_header().encode(),
        "opponents.h": opponents_header().encode(),
        "career_data.h": career_header().encode(),
        "court_projection.h": projection.encode(),
        "asm_shared.inc": asm_include(header).encode(),
        "select.pic": select_pic,
        "select.map": select_map,
        "select.pal": select_pal,
        "portrait.pic": portrait_pic,
        "portrait_m.map": portrait_m,
        "portrait_f.map": portrait_f,
        "bust.pic": bust_pic,
        "bust_m.map": bust_m,
        "bust_f.map": bust_f,
        "closeup.map": closeup_map,
        "park.pic": park_pic,
        "park.map": park_map,
        "park.pal": park_pal,
    }
    files.update(venue_files)
    sfx_it, sfx_header, sfx_seconds = sfx_assets()
    files["sfx.it"] = sfx_it
    files["sfx.h"] = sfx_header.encode()
    # ADR-031: one ambience module per venue, in venue order; the Makefile
    # lists them after sfx.it (smconv needs the effects first).
    venues = json.loads((paths.src / "venues.json").read_text("utf-8"))
    for i, venue in enumerate(venues["venues"]):
        files[f"ambience_{i}.it"] = ambience_module(venue["ambience"], 100 + i)
    budget = {"court_tiles": court_tiles, "ground_tiles": ground_tiles, "hud_tiles": hud_tiles,
              "obj_tiles": obj_tiles, "select_tiles": select_tiles,
              "portrait_tiles": portrait_tiles, "bust_tiles": bust_tiles,
              "park_tiles": park_tiles}
    return files, budget


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source", type=Path,
                        help="alternate assets/source (validation fixtures)")
    parser.add_argument("--validate-only", action="store_true",
                        help="run every validation without writing outputs")
    args = parser.parse_args()
    if args.source:
        paths.src = args.source
    if args.validate_only:
        generated_files()
        print("asset validation passed")
        return
    expected, budget = generated_files()
    paths.out.mkdir(parents=True, exist_ok=True)
    if args.check:
        failures = [name for name, data in expected.items()
                    if not (paths.out / name).exists() or
                    (paths.out / name).read_bytes() != data]
        if failures:
            raise SystemExit("asset validation failed: " + ", ".join(failures))
        print("asset validation passed")
        return
    for name, data in expected.items():
        path = paths.out / name
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    report = {name: {"bytes": len(data),
                     "sha256": hashlib.sha256(data).hexdigest()}
              for name, data in expected.items()}
    report["_budget"] = budget
    (paths.out / "sizes.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n",
                      encoding="utf-8")
    print("generated assets: court %(court_tiles)d tiles, hud %(hud_tiles)d "
          "tiles, obj %(obj_tiles)d tiles, select %(select_tiles)d tiles, "
          "portraits %(portrait_tiles)d tiles, busts %(bust_tiles)d tiles" % budget)


if __name__ == "__main__":
    main()
